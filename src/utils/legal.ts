/** True until this install has accepted the current version of the terms. */
export const needsTerms = (state: Pick<LocalState, 'termsAcceptedAt' | 'termsVersion'>) =>
  !state.termsAcceptedAt || state.termsVersion !== TERMS_VERSION;

/** "Зөвшөөрч эхлэх" accepts the terms and the AI disclosure together; "AI-гүйгээр эхлэх" accepts the terms only. */
export function withTerms(state: LocalState, ai: boolean, now = new Date()): LocalState {
  const accepted = { ...state, termsAcceptedAt: now.toISOString(), termsVersion: TERMS_VERSION };
  return ai ? withConsent(accepted, now) : accepted;
}
